Driver_SPD2010::Driver_SPD2010(uint16_t width, uint16_t height)
    : _width(width), _height(height), _qspi(nullptr), _frameBuffer(nullptr),
      _transferBuffer(nullptr), _transferCapacityPixels(0),
      _windowX0(0), _windowY0(0), _windowX1(width - 1),
      _windowY1(height - 1), _cursorX(0), _cursorY(0), _sleeping(false) {
    IDriver::_width = width;
    IDriver::_height = height;
}

Driver_SPD2010::~Driver_SPD2010() {
    if (_qspi) (void)_qspi->waitForTransfer();
#if SEEED_GFX_HAS_ESP32S3_LCD
    if (_frameBuffer) heap_caps_free(_frameBuffer);
    if (_transferBuffer) heap_caps_free(_transferBuffer);
#endif
}

bool Driver_SPD2010::runInitSequence() {
    // Match esp_lcd_spd2010's lifecycle: reset first, then explicitly select
    // the user command page and configure rotation/color depth before the
    // vendor-specific table. The vendor table does not replace MADCTL or
    // COLMOD; omitting COLMOD leaves RGB565 transfers undefined.
    if (!_qspi->writeCommandData(0x01, nullptr, 0)) return false;
    delay(120);

    const uint8_t userPage[3] = {0x20, 0x10, 0x00};
    if (!_qspi->writeCommandData(0xFF, userPage, sizeof(userPage))) return false;
    const uint8_t madctl = 0x00;
    if (!_qspi->writeCommandData(0x36, &madctl, 1)) return false;
    const uint8_t colmod = 0x55;
    if (!_qspi->writeCommandData(0x3A, &colmod, 1)) return false;

    size_t offset = 0;
    while (offset < sizeof(kSpd2010Init)) {
        const uint8_t cmd = kSpd2010Init[offset++];
        const uint8_t len = kSpd2010Init[offset++];
        if (offset + len > sizeof(kSpd2010Init)) return false;
        if (!_qspi->writeCommandData(cmd, kSpd2010Init + offset, len)) {
            return false;
        }
        offset += len;
        if (cmd == 0x11 && len == 0) delay(120);
    }
    return _qspi->writeCommandData(0x29, nullptr, 0);
}

bool Driver_SPD2010::init(IBus& bus) {
    _bus = &bus;
    // ProductCatalog constructs this driver only with Bus_ESP32QSPI. Avoid
    // RTTI because the ESP32 Arduino core is built with -fno-rtti.
    _qspi = static_cast<Bus_ESP32QSPI*>(&bus);
#if SEEED_GFX_HAS_ESP32S3_LCD
    const size_t framePixels =
        static_cast<size_t>(_width) * static_cast<size_t>(_height);
    _frameBuffer = static_cast<uint16_t*>(
        heap_caps_calloc(framePixels, sizeof(uint16_t),
                         MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT));
    // A horizontal logical run is either one native row, or after a 90-degree
    // rotation a four-pixel-wide aligned column spanning up to nativeHeight().
    _transferCapacityPixels =
        static_cast<size_t>(_width) >
                static_cast<size_t>(_height) * 4U
            ? static_cast<size_t>(_width)
            : static_cast<size_t>(_height) * 4U;
    _transferBuffer = static_cast<uint16_t*>(
        heap_caps_malloc(_transferCapacityPixels * sizeof(uint16_t),
                         MALLOC_CAP_DMA | MALLOC_CAP_INTERNAL));
    if (!_frameBuffer || !_transferBuffer) {
        if (_frameBuffer) {
            heap_caps_free(_frameBuffer);
            _frameBuffer = nullptr;
        }
        if (_transferBuffer) {
            heap_caps_free(_transferBuffer);
            _transferBuffer = nullptr;
        }
        _transferCapacityPixels = 0;
        return false;
    }
#else
    return false;
#endif
    if (!runInitSequence()) {
        setOperationError(DriverOperationError::CommunicationFailed);
        return false;
    }
    setAddrWindow(0, 0, width() - 1, height() - 1);
    return true;
}

void Driver_SPD2010::setRotation(uint8_t rotation) {
    _rotation = rotation & 3U;
    // SPD2010 has no controller-side XY swap. storeAndFlush() maps each
    // logical scan-line segment into the native shadow framebuffer instead.
    setAddrWindow(0, 0, width() - 1, height() - 1);
}

void Driver_SPD2010::invertDisplay(bool invert) {
    if (_qspi) (void)_qspi->writeCommandData(invert ? 0x21 : 0x20, nullptr, 0);
}

void Driver_SPD2010::displayOn() {
    if (_qspi) {
        (void)_qspi->writeCommandData(0x11, nullptr, 0);
        delay(120);
        (void)_qspi->writeCommandData(0x29, nullptr, 0);
    }
    _sleeping = false;
}

void Driver_SPD2010::displayOff() {
    if (_qspi) (void)_qspi->writeCommandData(0x28, nullptr, 0);
}

void Driver_SPD2010::sleep() {
    if (_qspi) {
        (void)_qspi->waitForTransfer();
        (void)_qspi->writeCommandData(0x10, nullptr, 0);
        delay(120);
    }
    _sleeping = true;
}

void Driver_SPD2010::wake() {
    if (_sleeping) displayOn();
}

void Driver_SPD2010::setAddrWindow(uint16_t xs, uint16_t ys,
                                   uint16_t xe, uint16_t ye) {
    _windowX0 = xs < _width ? xs : static_cast<uint16_t>(_width - 1);
    _windowY0 = ys < _height ? ys : static_cast<uint16_t>(_height - 1);
    _windowX1 = xe < _width ? xe : static_cast<uint16_t>(_width - 1);
    _windowY1 = ye < _height ? ye : static_cast<uint16_t>(_height - 1);
    if (_windowX1 < _windowX0) _windowX1 = _windowX0;
    if (_windowY1 < _windowY0) _windowY1 = _windowY0;
    _cursorX = _windowX0;
    _cursorY = _windowY0;
}

uint16_t Driver_SPD2010::contiguousCount(size_t remaining) const {
    const uint16_t rowRemaining =
        static_cast<uint16_t>(_windowX1 - _cursorX + 1U);
    return remaining < rowRemaining ? static_cast<uint16_t>(remaining)
                                    : rowRemaining;
}

bool Driver_SPD2010::sendWindow(uint16_t x0, uint16_t y0,
                                uint16_t x1, uint16_t y1) {
    const uint8_t columns[4] = {
        static_cast<uint8_t>(x0 >> 8), static_cast<uint8_t>(x0),
        static_cast<uint8_t>(x1 >> 8), static_cast<uint8_t>(x1)
    };
    const uint8_t rows[4] = {
        static_cast<uint8_t>(y0 >> 8), static_cast<uint8_t>(y0),
        static_cast<uint8_t>(y1 >> 8), static_cast<uint8_t>(y1)
    };
    return _qspi->writeCommandData(0x2A, columns, sizeof(columns)) &&
           _qspi->writeCommandData(0x2B, rows, sizeof(rows));
}

void Driver_SPD2010::logicalToNative(uint16_t x, uint16_t y,
                                     uint16_t& nativeX,
                                     uint16_t& nativeY) const {
    switch (_rotation) {
        case 0:
            nativeX = x;
            nativeY = y;
            break;
        case 1:
            nativeX = static_cast<uint16_t>(_width - 1U - y);
            nativeY = x;
            break;
        case 2:
            nativeX = static_cast<uint16_t>(_width - 1U - x);
            nativeY = static_cast<uint16_t>(_height - 1U - y);
            break;
        default:
            nativeX = y;
            nativeY = static_cast<uint16_t>(_height - 1U - x);
            break;
    }
}

